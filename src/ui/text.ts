export type UiKey = keyof typeof UI_TEXT
export type UiText = Record<UiKey, string>
/** The translator a site gives: the same shape as the plugin's `i18n.t`. */
export type Translate = (key: string, vars?: Record<string, string | number>) => string | undefined | null

/** The words with `{vars}` left in, translated where `t` has them. Plain strings, safe to send to the browser. */
export function uiText(t?: Translate | null): UiText {
  const out = { ...UI_TEXT } as UiText
  if (!t) return out
  for (const key of Object.keys(UI_TEXT) as UiKey[]) {
    const full = `sampleKits.ui.${key}`
    try {
      const v = t(full)
      if (typeof v === 'string' && v && v !== full) out[key] = v
    } catch {
      // Missing: keep English.
    }
  }
  return out
}

/** One string, with `{vars}` filled in. */
export const tx = (text: Partial<UiText> | undefined, key: UiKey, vars: Record<string, string | number> = {}) =>
  String(text?.[key] ?? UI_TEXT[key]).replace(/\{(\w+)\}/g, (all, k: string) => (k in vars ? String(vars[k]) : all))

/** A date as words, in UTC (dates from the server are stored in UTC), e.g. "March 3, 2027". */
export const day = (iso: string | null | undefined, locale = 'en-US') => {
  if (!iso) return ''
  const d = new Date(iso.length === 10 ? `${iso}T00:00:00Z` : iso)
  return Number.isNaN(d.getTime()) ? '' : d.toLocaleDateString(locale, { year: 'numeric', month: 'long', day: 'numeric', timeZone: 'UTC' })
}

/** The keyof for a text key built from data, e.g. `reason_changed_mind`. */
export const keyOf = (prefix: string, value: string) => `${prefix}${value.replace(/-/g, '_')}` as UiKey
